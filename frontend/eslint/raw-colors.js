// esquery's regex syntax has no \b, so word boundaries are spelled out.
const START = "(^|[^a-zA-Z0-9_-])";
const END = "([^a-zA-Z0-9_-]|$)";

// Only where a value is used as a color, so words like "orange" in ordinary text pass.
const COLOR_PROPERTY = "/color|background|border|fill|stroke|outline|shadow/i";
const COLOR_ATTRIBUTE = "/^(color|fill|stroke|background)$/";

export const RAW_COLOR_SELECTORS = [
  `Literal[value=/^${HEX}$/]`,
  `Literal[value=/^${COLOR_FUNCTION}/]`,
  `TemplateElement[value.raw=/${HEX}${END}/]`,
  `TemplateElement[value.raw=/${START}${COLOR_FUNCTION}/]`,
  `Property[key.name=${COLOR_PROPERTY}] > Literal[value=/${START}(${NAMED_COLORS})${END}/i]`,
  `Property[key.name=${COLOR_PROPERTY}] TemplateElement[value.raw=/${START}(${NAMED_COLORS})${END}/i]`,
  `JSXAttribute[name.name=${COLOR_ATTRIBUTE}] Literal[value=/^(${NAMED_COLORS})$/i]`,
].map((selector) => ({ selector, message: MESSAGE }));
